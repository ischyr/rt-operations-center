// ── Config generators ─────────────────────────────────────────────────────────
function genSocat(hop) {
  const lp = hop.listenPort || 443;
  const fh = hop.forwardHost || 'NEXT_HOP_IP';
  const fp = hop.forwardPort || 443;
  return `#!/bin/bash
# Socat TCP Redirector — ${hop.label || hop.id}
# Generated by Red Team Operations Center

# Install socat:
# apt install socat -y

# Foreground (testing):
socat TCP-LISTEN:${lp},reuseaddr,fork TCP:${fh}:${fp}

# Systemd service (production):
cat > /etc/systemd/system/redirector.service << 'EOF'
[Unit]
Description=Socat Redirector
After=network.target

[Service]
ExecStart=/usr/bin/socat TCP-LISTEN:${lp},reuseaddr,fork TCP:${fh}:${fp}
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable --now redirector

# Firewall:
iptables -A INPUT  -p tcp --dport ${lp} -j ACCEPT
iptables -A OUTPUT -p tcp --dport ${fp} -j ACCEPT`;
}

function genNginx(hop) {
  const lp     = hop.listenPort  || 443;
  const fh     = hop.forwardHost || 'TEAM_SERVER_IP';
  const fp     = hop.forwardPort || 443;
  const domain = hop.domain      || 'redirector.example.com';
  const ah     = hop.authHeader  || 'X-Custom-Auth';
  const av     = hop.authValue   || 'ChangeMe123!';
  const uri    = hop.c2Profile   || '/jquery-3.3.1.min.js';
  const ahNorm = ah.replace(/-/g, '_');

  return `# Nginx HTTPS Redirector — ${hop.label || hop.id}
# /etc/nginx/sites-available/redirector

upstream c2_backend {
    server ${fh}:${fp} max_fails=3 fail_timeout=30s;
}

server {
    listen 80;
    server_name ${domain};
    return 301 https://$host$request_uri;
}

server {
    listen ${lp} ssl http2;
    server_name ${domain};

    ssl_certificate     /etc/letsencrypt/live/${domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         HIGH:!aNULL:!MD5;

    server_tokens off;
    add_header Server "Microsoft-IIS/10.0";

    # Layer 1: Block scanners by User-Agent
    if ($http_user_agent ~* (nmap|masscan|zgrab|shodan|censys|curl|python|go-http|ruby|nikto|sqlmap|nuclei)) {
        return 301 https://www.microsoft.com;
    }

    # Layer 2: Require custom auth header
    if ($http_${ahNorm} != "${av}") {
        return 301 https://www.microsoft.com;
    }

    # Layer 3: Only allow C2 URI paths
    location ~ ^${uri} {
        proxy_pass          https://c2_backend;
        proxy_ssl_verify    off;
        proxy_set_header    Host $host;
        proxy_set_header    X-Forwarded-For $remote_addr;
        proxy_set_header    ${ah} ${av};
        proxy_hide_header   X-Powered-By;
        proxy_connect_timeout 10s;
        proxy_read_timeout    30s;
    }

    # Layer 4: Catch-all redirect
    location / {
        return 301 https://www.microsoft.com;
    }
}`;
}

function genApache(hop) {
  const fh = hop.forwardHost || 'NEXT_HOP_IP';
  const fp = hop.forwardPort || 443;
  const ah = hop.authHeader  || 'X-Custom-Auth';
  const av = hop.authValue   || 'ChangeMe123!';
  return `# Apache mod_rewrite Redirector — ${hop.label || hop.id}
# a2enmod rewrite proxy proxy_http ssl headers

<VirtualHost *:443>
    SSLEngine on
    SSLCertificateFile    /etc/letsencrypt/live/DOMAIN/fullchain.pem
    SSLCertificateKeyFile /etc/letsencrypt/live/DOMAIN/privkey.pem

    ServerTokens Prod
    ServerSignature Off
    Header always set Server "Microsoft-IIS/10.0"

    SSLProxyEngine On
    SSLProxyVerify none
    SSLProxyCheckPeerCN off

    RewriteEngine On

    # Block bad user agents
    RewriteCond %{HTTP_USER_AGENT} (nmap|masscan|zgrab|shodan|censys|python|nikto|nuclei) [NC]
    RewriteRule .* https://www.microsoft.com/ [L,R=301]

    # Require custom auth header
    RewriteCond %{HTTP:${ah}} !^${av}$
    RewriteRule .* https://www.microsoft.com/ [L,R=301]

    # Block recon paths
    RewriteCond %{REQUEST_URI} \\.(php|asp|env|git|htaccess)$ [NC]
    RewriteRule .* https://www.microsoft.com/ [L,R=301]

    # Forward valid traffic
    RewriteRule ^(.*)$ https://${fh}:${fp}$1 [P,L]
    ProxyPassReverse / https://${fh}:${fp}/
</VirtualHost>`;
}

function genCloudflare(hop) {
  const fh = hop.forwardHost || 'NGINX_REDIRECTOR_IP';
  const fp = hop.forwardPort || 443;
  const ah = hop.authHeader  || 'X-Custom-Auth';
  const av = hop.authValue   || 'ChangeMe123!';
  return `// Cloudflare Worker — CDN Redirector
// Deploy: Workers & Pages → Create Worker
// Generated by Red Team Operations Center

const UPSTREAM  = 'https://${fh}:${fp}';
const AUTH_HDR  = '${ah}';
const AUTH_VAL  = '${av}';
const DECOY_URL = 'https://www.microsoft.com';

const BAD_UA = ['nmap','masscan','zgrab','shodan','censys','python','go-http','nuclei','nikto'];

export default {
  async fetch(request, env, ctx) {
    const ua = (request.headers.get('User-Agent') || '').toLowerCase();

    // Layer 1: UA filter
    if (BAD_UA.some(b => ua.includes(b)))
      return Response.redirect(DECOY_URL, 301);

    // Forward with auth header injected
    const url = new URL(request.url);
    url.hostname = '${fh}';

    const headers = new Headers(request.headers);
    headers.set(AUTH_HDR, AUTH_VAL);

    const req = new Request(url.toString(), {
      method:   request.method,
      headers,
      body:     ['GET','HEAD'].includes(request.method) ? undefined : request.body,
      redirect: 'manual',
    });

    try {
      const res = await fetch(req, { cf: { ssl: true } });
      const r   = new Response(res.body, res);
      r.headers.delete('X-Powered-By');
      r.headers.delete('Server');
      return r;
    } catch {
      return Response.redirect(DECOY_URL, 301);
    }
  },
};

/*
 * Dashboard settings:
 * Workers → Settings → Variables → AUTH_VAL = ${av} (Encrypted)
 * Workers → Triggers → Add Route: *.<your-domain>.com/* → this worker
 * DNS → Enable "Orange Cloud" (CDN proxy) on your A record
 * SSL/TLS → Full (strict)
 */`;
}

function genLambda(hop) {
  const fh = hop.forwardHost || 'NGINX_REDIRECTOR_IP';
  const fp = hop.forwardPort || 443;
  const ah = hop.authHeader  || 'X-Custom-Auth';
  const av = hop.authValue   || 'ChangeMe123!';
  return `# AWS Lambda Serverless Redirector — ${hop.label || hop.id}
# lambda_function.py

import urllib3

UPSTREAM = 'https://${fh}:${fp}'
AUTH_HDR = '${ah}'
AUTH_VAL = '${av}'
DECOY    = 'https://www.microsoft.com'
BAD_UA   = ['nmap','masscan','zgrab','shodan','python','nuclei']

http = urllib3.PoolManager(cert_reqs='CERT_NONE')

def lambda_handler(event, context):
    headers = event.get('headers') or {}
    ua = (headers.get('user-agent') or '').lower()

    if any(b in ua for b in BAD_UA):
        return {'statusCode': 301, 'headers': {'Location': DECOY}}

    path   = event.get('rawPath', '/')
    qs     = event.get('rawQueryString', '')
    method = event.get('requestContext', {}).get('http', {}).get('method', 'GET')
    body   = event.get('body', '')

    fwd = dict(headers)
    fwd[AUTH_HDR] = AUTH_VAL

    url  = f'{UPSTREAM}{path}{"?" + qs if qs else ""}'
    resp = http.request(method, url, headers=fwd, body=body or None, redirect=False)

    return {
        'statusCode': resp.status,
        'headers':    dict(resp.headers),
        'body':       resp.data.decode('utf-8', errors='replace'),
    }

# Deploy:
# zip lambda.zip lambda_function.py
# aws lambda create-function \\
#   --function-name c2-redirector \\
#   --runtime python3.11 \\
#   --role arn:aws:iam::ACCOUNT_ID:role/lambda-basic \\
#   --handler lambda_function.lambda_handler \\
#   --zip-file fileb://lambda.zip`;
}

function generateConfig(hop) {
  switch (hop.type) {
    case 'socat':      return genSocat(hop);
    case 'nginx':      return genNginx(hop);
    case 'apache':     return genApache(hop);
    case 'cloudflare': return genCloudflare(hop);
    case 'lambda':     return genLambda(hop);
    case 'beacon':
      return `# Beacon / Implant — ${hop.label || hop.id}
# Sleep:    ${hop.sleep || 60}s ± ${hop.jitter || 30}%
# Listener: ${hop.forwardHost || 'TEAM_SERVER_IP'}:${hop.listenPort || 443}
# Profile:  ${hop.c2Profile || 'default'}`;
    case 'c2':
      return `# Team Server / C2 — ${hop.label || hop.id}
# IP:      ${hop.forwardHost || 'TEAM_SERVER_IP'}
# Port:    ${hop.listenPort || 443}
# Profile: ${hop.c2Profile || 'default'}`;
    default: return '# No config for this hop type';
  }
}

