const DEFAULT_CHAIN = [
  { id: 'h1', type: 'beacon',     label: 'Implant',           listenPort: '',  forwardHost: '',             status: 'active', sleep: 60, jitter: 30 },
  { id: 'h2', type: 'cloudflare', label: 'CF Worker',         listenPort: 443, forwardHost: '',             domain: 'cdn.example.com',   authHeader: 'X-Custom-Auth', authValue: 'RedTeam2024!', status: 'active' },
  { id: 'h3', type: 'nginx',      label: 'HTTPS Redirector',  listenPort: 443, forwardHost: '',             domain: 'redir.example.com', authHeader: 'X-Custom-Auth', authValue: 'RedTeam2024!', c2Profile: '/jquery-3.3.1.min.js', status: 'active' },
  { id: 'h4', type: 'c2',         label: 'Team Server',       listenPort: 443, forwardHost: '10.10.0.204',  status: 'active' },
];

let _nid = 10;
const nextId = () => `h${_nid++}`;

// ── Main ──────────────────────────────────────────────────────────────────────
export default function RedirectorChainView() {
  const toast = useToast();
  const [hops,        setHops]        = useState(DEFAULT_CHAIN);
  const [selectedId,  setSelectedId]  = useState('h3');
  const [chainName,   setChainName]   = useState('Primary Redirector Chain');
  const [chainActive, setChainActive] = useState(true);
  const [newType,     setNewType]     = useState('');

  const selectedHop = hops.find(h => h.id === selectedId) || null;
  const activeCnt   = hops.filter(h => h.status !== 'burned').length;
  const burnedCnt   = hops.filter(h => h.status === 'burned').length;

  const addHop = (type) => {
    if (!type) return;
    const ht  = HOP_TYPES[type];
    const hop = {
      id: nextId(), type, label: ht.label,
      listenPort: 443, forwardHost: '', domain: '',
      authHeader: 'X-Custom-Auth', authValue: 'ChangeMe123!',
      c2Profile: '/jquery-3.3.1.min.js', status: 'active',
    };
    setHops(prev => [...prev, hop]);
    setSelectedId(hop.id);
    setNewType('');
  };

  const updateHop = (updated) =>
    setHops(prev => prev.map(h => h.id === updated.id ? updated : h));

  const deleteHop = (id) => {
    setHops(prev => {
      const next = prev.filter(h => h.id !== id);
      if (selectedId === id) setSelectedId(next[0]?.id || null);
      return next;
    });
  };

  const moveHop = (idx, dir) => {
    setHops(prev => {
      const arr  = [...prev];
      const tgt  = idx + dir;
      if (tgt < 0 || tgt >= arr.length) return arr;
      [arr[idx], arr[tgt]] = [arr[tgt], arr[idx]];
      return arr;
    });
  };

  const downloadAll = () => {
    hops.forEach(hop => {
      const cfg = generateConfig(hop);
      const ext = hop.type === 'cloudflare' ? 'js' : hop.type === 'lambda' ? 'py' : hop.type === 'nginx' ? 'conf' : 'sh';
      const blob = new Blob([cfg], { type: 'text/plain' });
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = `${hop.label || hop.type}.${ext}`;
      a.click();
    });
    toast({ title: `${hops.length} config files downloaded`, status: 'success', duration: 2000 });
  };

  // OPSEC checks
  const opsec = [
    { label: 'CDN layer present',        ok: hops.some(h => h.type === 'cloudflare') },
    { label: 'Auth header chaining',     ok: hops.some(h => h.authHeader) },
    { label: 'HTTPS redirector (nginx/apache)', ok: hops.some(h => ['nginx','apache'].includes(h.type)) },
    { label: 'Beacon sleep ≥ 30s',      ok: hops.some(h => h.type === 'beacon' && Number(h.sleep) >= 30) },
    { label: 'Multi-hop chain (≥ 3)',   ok: hops.length >= 3 },
    { label: 'No burned hops',          ok: burnedCnt === 0 },
  ];
  const opsecScore = opsec.filter(o => o.ok).length;

  return (
    <Box px={6} pb={12} pt={5}>

      {/* ── Header ────────────────────────────────────────────────────────── */}
      <Flex justify="space-between" align="flex-start" mb={5} flexWrap="wrap" gap={3}>
        <Box>
          <Heading fontSize="2xl" fontWeight="bold" color="var(--dash-text-primary)" lineHeight={1.2}>
            Redirector <Text as="span" color="red.400">Chain Planner</Text>
          </Heading>
          <Text fontSize="12px" color="var(--dash-text-secondary)" mt={1}>
            Design multi-hop redirector chains · generate exact configs per hop · track active vs burned
          </Text>
        </Box>
        <Button size="sm" leftIcon={<DownloadIcon />} borderRadius="8px"
          bg={`${ACCENT}20`} color={ACCENT} border={`1px solid ${ACCENT}50`}
          _hover={{ bg: `${ACCENT}35` }} fontWeight="bold" fontSize="12px"
          onClick={downloadAll}>
          Export All Configs
        </Button>
      </Flex>

      {/* ── Info banner ───────────────────────────────────────────────────── */}
      <Box mb={5} px={4} py={3} borderRadius="10px"
        bg="rgba(99,179,237,0.07)" border="1px solid rgba(99,179,237,0.25)">
        <Flex align="center" gap={2} mb={1.5}>
          <Box w="6px" h="6px" borderRadius="full" bg={ACCENT} />
          <Text fontSize="10px" fontWeight="bold" color={ACCENT}
            textTransform="uppercase" letterSpacing="wider">Architecture</Text>
        </Flex>
        <Flex gap={4} flexWrap="wrap">
          {[
            'Beacon → CDN (Cloudflare Worker) → HTTPS Redirector (Nginx/Apache) → Team Server',
            'Custom auth headers chain hops together and block automated scanners',
            'Mark hops as burned when detected — track OPSEC posture per chain',
          ].map(t => (
            <Flex key={t} align="center" gap={1.5}>
              <Box w="4px" h="4px" borderRadius="full" bg={ACCENT} flexShrink={0} />
              <Text fontSize="11px" color="var(--dash-text-secondary)">{t}</Text>
            </Flex>
          ))}
        </Flex>
      </Box>

      {/* ── Stat row ──────────────────────────────────────────────────────── */}
      <SimpleGrid columns={4} gap={4} mb={6}>
        <StatCard label="Total Hops"   value={hops.length}  color={ACCENT}  delay={0} />
        <StatCard label="Active"        value={activeCnt}    color={GREEN}   delay={0.04} />
        <StatCard label="Burned"        value={burnedCnt}    color={RED}     delay={0.08} />
        <StatCard label="OPSEC Score"   value={`${opsecScore}/${opsec.length}`} color={opsecScore >= 5 ? GREEN : opsecScore >= 3 ? ORANGE : RED} delay={0.12} />
      </SimpleGrid>

      {/* ── Chain diagram ─────────────────────────────────────────────────── */}
      <Card mb={6} accentColor={ACCENT}>
        <Box px={5} py={4}>
          <Flex align="center" justify="space-between" mb={4}>
            <Flex align="center" gap={3}>
              <Input value={chainName} onChange={e => setChainName(e.target.value)}
                variant="unstyled" fontSize="13px" fontWeight="bold"
                color="var(--dash-text-primary)" w="260px"
                _placeholder={{ color: 'var(--dash-text-muted)' }} />
              <Flex align="center" gap={2}>
                <Switch size="sm" colorScheme="green"
                  isChecked={chainActive} onChange={e => setChainActive(e.target.checked)} />
                <Text fontSize="11px" fontWeight="semibold"
                  color={chainActive ? GREEN : RED}>
                  {chainActive ? 'Active' : 'Burned'}
                </Text>
              </Flex>
            </Flex>
            <Flex align="center" gap={2}>
              <Select value={newType} onChange={e => { addHop(e.target.value); }}
                placeholder="+ Add hop" size="sm" w="160px"
                bg="rgba(255,255,255,0.05)" borderColor="rgba(255,255,255,0.1)"
                borderRadius="8px" fontSize="12px" color="var(--dash-text-primary)"
                _hover={{ borderColor: `${ACCENT}50` }}
                focusBorderColor={`${ACCENT}80`}
                sx={{ '& option': { background: '#1a1a1f !important' } }}>
                {Object.entries(HOP_TYPES).map(([k, v]) => (
                  <option key={k} value={k}>{v.label}</option>
                ))}
              </Select>
            </Flex>
          </Flex>
          <ChainDiagram hops={hops} selectedId={selectedId} onSelect={setSelectedId} />
        </Box>
      </Card>

      {/* ── Main: hop list + config ────────────────────────────────────────── */}
      <Flex gap={6} align="flex-start">

        {/* Left: hop list + OPSEC */}
        <Box w="380px" flexShrink={0}>
          <Text fontSize="10px" color="var(--dash-text-muted)" textTransform="uppercase"
            letterSpacing="wider" fontWeight="bold" mb={3}>
            Hops ({hops.length})
          </Text>

          <Flex direction="column" gap={3} mb={4}>
            <AnimatePresence>
              {hops.map((hop, i) => (
                <HopRow key={hop.id} hop={hop} idx={i} total={hops.length}
                  onChange={updateHop} onDelete={deleteHop}
                  selected={selectedId === hop.id}
                  onSelect={setSelectedId}
                  onMove={moveHop} />
              ))}
            </AnimatePresence>
            {hops.length === 0 && (
              <Box px={5} py={8} borderRadius="12px" textAlign="center"
                bg="var(--dash-card-bg)" border="1px solid var(--dash-card-border)">
                <Text fontSize="12px" color="var(--dash-text-muted)">
                  No hops yet — add one from the chain diagram above
                </Text>
              </Box>
            )}
          </Flex>

          {/* OPSEC checklist */}
          <Card accentColor={opsecScore >= 5 ? GREEN : ORANGE}>
            <Box p={5}>
              <Flex align="center" justify="space-between" mb={3}>
                <Label>OPSEC Checklist</Label>
                <Flex align="center" gap={1.5} px={2} py="2px" borderRadius="5px"
                  bg={opsecScore >= 5 ? `${GREEN}15` : `${ORANGE}15`}
                  border={opsecScore >= 5 ? `1px solid ${GREEN}40` : `1px solid ${ORANGE}40`}>
                  <Text fontSize="9px" fontWeight="bold"
                    color={opsecScore >= 5 ? GREEN : ORANGE}>
                    {opsecScore}/{opsec.length}
                  </Text>
                </Flex>
              </Flex>
              <Flex direction="column" gap={2}>
                {opsec.map((item, i) => (
                  <Flex key={i} align="center" gap={2.5}
                    py={1.5} borderBottom={i < opsec.length - 1 ? '1px solid rgba(255,255,255,0.05)' : 'none'}>
                    <Flex w="16px" h="16px" borderRadius="4px" flexShrink={0}
                      bg={item.ok ? `${GREEN}15` : 'rgba(255,255,255,0.05)'}
                      border={item.ok ? `1px solid ${GREEN}40` : '1px solid rgba(255,255,255,0.1)'}
                      align="center" justify="center">
                      {item.ok && <CheckIcon boxSize={2} color={GREEN} />}
                    </Flex>
                    <Text fontSize="11px" color={item.ok ? 'var(--dash-text-primary)' : 'var(--dash-text-muted)'}>
                      {item.label}
                    </Text>
                  </Flex>
                ))}
              </Flex>
            </Box>
          </Card>
        </Box>

        {/* Right: config viewer */}
        <Box flex={1} minW={0} minH="600px">
          <ConfigPanel hop={selectedHop} />
        </Box>
      </Flex>
    </Box>
  );
}
